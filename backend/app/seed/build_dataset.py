def build() -> list[dict]:
    out = []
    for cid, et, cli, msg, ag, tools, conf, esp, reglas in CASOS:
        out.append(
            {
                "id": cid,
                "etiqueta": et,
                "cliente_id": cli,
                "sesion_nueva": True,
                "mensaje": msg,
                "agente_esperado": ag,
                "tools_esperadas": tools,
                "respuesta_esperada": esp,
                "reglas_a_verificar": reglas,
                "debe_pedir_confirmacion": conf,
            }
        )
    return out


